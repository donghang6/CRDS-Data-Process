def infer_uncertainty_csv(csv_path: Path) -> Path:
    parts = csv_path.resolve().parts
    try:
        continuum_idx = parts.index("continuum")
        cia_idx = continuum_idx + 1
        if parts[cia_idx] != "CIA":
            raise ValueError
    except (ValueError, IndexError):
        raise SystemExit(
            "Cannot infer --uncertainty-csv from path. Please pass it explicitly."
        ) from None

    group_parts = parts[cia_idx + 1 : -1]
    if len(group_parts) < 2:
        raise SystemExit(
            "Cannot infer --uncertainty-csv because the continuum path is not "
            "continuum/CIA/{temperature}/{gas pressure}/..."
        )
    return PROJECT_ROOT / "output" / "results" / "uncertainty" / "CIA" / Path(*group_parts) / "tau_uncertainty.csv"


def infer_pressure_label(csv_path: Path) -> str:
    parent = csv_path.resolve().parent
    return parent.name


def default_output_path(csv_path: Path) -> Path:
    return csv_path.with_name(f"{csv_path.stem}_mc_uncertainty.csv")


def normalize_range(values: list[float] | tuple[float, float] | None) -> tuple[float, float] | None:
    if values is None:
        return None
    start, end = float(values[0]), float(values[1])
    return (start, end) if start <= end else (end, start)


def read_base_table(args: argparse.Namespace) -> pd.DataFrame:
    csv_path = args.csv_path.expanduser().resolve()
    if not csv_path.is_file():
        raise SystemExit(f"Input CSV does not exist: {csv_path}")
    df = pd.read_csv(csv_path)
    required = [args.x_column]
    if args.fit_method == "continuum-step2":
        required.append(args.tau_column)
    else:
        required.append(args.fit_column)
    missing = [col for col in required if col not in df.columns]
    if missing:
        raise SystemExit(f"{csv_path} is missing columns: {', '.join(missing)}")
    return df


def read_uncertainty_table(args: argparse.Namespace) -> pd.DataFrame:
    uncertainty_csv = (
        args.uncertainty_csv.expanduser().resolve()
        if args.uncertainty_csv
        else infer_uncertainty_csv(args.csv_path)
    )
    if not uncertainty_csv.is_file():
        raise SystemExit(f"Uncertainty CSV does not exist: {uncertainty_csv}")
    df = pd.read_csv(uncertainty_csv)
    missing = [
        col
        for col in (args.uncertainty_x_column, args.uncertainty_column)
        if col not in df.columns
    ]
    if missing:
        raise SystemExit(f"{uncertainty_csv} is missing columns: {', '.join(missing)}")
    return df


def attach_tau_uncertainty(
    base_df: pd.DataFrame,
    uncertainty_df: pd.DataFrame,
    args: argparse.Namespace,
) -> pd.DataFrame:
    base = base_df.copy()
    base["_mc_original_order"] = np.arange(len(base), dtype=int)
    left = base.sort_values(args.x_column)
    right = (
        uncertainty_df[[args.uncertainty_x_column, args.uncertainty_column]]
        .dropna()
        .sort_values(args.uncertainty_x_column)
        .rename(columns={
            args.uncertainty_x_column: "_mc_unc_wavenumber",
            args.uncertainty_column: "tau_mc_input_uncertainty_us",
        })
    )
    merged = pd.merge_asof(
        left,
        right,
        left_on=args.x_column,
        right_on="_mc_unc_wavenumber",
        direction="nearest",
        tolerance=float(args.merge_tolerance),
    )
    merged = merged.sort_values("_mc_original_order").drop(columns=["_mc_original_order"])
    if "_mc_unc_wavenumber" in merged.columns:
        merged = merged.drop(columns=["_mc_unc_wavenumber"])

    sigma = pd.to_numeric(merged["tau_mc_input_uncertainty_us"], errors="coerce")
    missing = int((~np.isfinite(sigma) | (sigma <= 0)).sum())
    if missing:
        raise SystemExit(
            f"{missing} rows did not receive a positive finite tau uncertainty. "
            "Increase --merge-tolerance or check the wavenumber grids."
        )
    return merged


def with_sampled_tau(
    base_df: pd.DataFrame,
    tau_column: str,
    sampled_tau: np.ndarray,
) -> pd.DataFrame:
    work = base_df.copy()
    work[tau_column] = sampled_tau
    if tau_column != "tau_us":
        work["tau_us"] = sampled_tau
    tau = pd.to_numeric(work["tau_us"], errors="coerce").to_numpy(dtype=float)
    work["loss_ppm_per_cm"] = TAU_US_TO_PPM_PER_CM / tau
    return work


def o2_fit_mask_from_table(work: pd.DataFrame, pressure_label: str) -> np.ndarray:
    if "o2_fit_used" in work.columns:
        return work["o2_fit_used"].astype(bool).to_numpy()

    hitran_work = _add_o2_hitran_subtraction(work, pressure_label=pressure_label)
    absorption_mask, _ = _hitran_absorption_mask(
        wavenumber=hitran_work["wavenumber"].to_numpy(dtype=float),
        hitran_loss=hitran_work["hitran_o2_loss_ppm_per_cm"].to_numpy(dtype=float),
    )
    finite = (
        np.isfinite(hitran_work["wavenumber"].to_numpy(dtype=float))
        & np.isfinite(hitran_work["loss_ppm_per_cm"].to_numpy(dtype=float))
    )
    return finite & ~absorption_mask


def continuum_step2_fit(
    work: pd.DataFrame,
    args: argparse.Namespace,
    active_mode: str,
    o2_fit_mask: np.ndarray | None,
) -> np.ndarray:
    wn = pd.to_numeric(work[args.x_column], errors="coerce").to_numpy(dtype=float)
    loss = pd.to_numeric(work["loss_ppm_per_cm"], errors="coerce").to_numpy(dtype=float)
    fit_mask = o2_fit_mask if active_mode == "o2" else None
    fitted_loss = _fit_loss_values(
        wn=wn,
        loss=loss,
        fit_mask=fit_mask,
        window_cm1=args.cia_fit_window,
        step_cm1=args.cia_fit_step,
        order=args.cia_fit_order,
        sigma=args.cia_fit_sigma,
        smooth_cm1=args.cia_fit_smooth,
        error_label=f"Monte Carlo {active_mode} Step 2 fit",
    )
    return TAU_US_TO_PPM_PER_CM / fitted_loss


def lmfit_spline_fit(
    work: pd.DataFrame,
    args: argparse.Namespace,
    y_column: str,
) -> np.ndarray:
    lmfit_spline.load_dependencies()
    output_column = "_mc_lmfit_spline_output"
    fit_range = normalize_range(args.fit_range)
    if args.region:
        if args.n_knots is not None:
            raise SystemExit("--region cannot be combined with --n-knots")
        lmfit_spline.fit_regional_splines(
            df=work,
            x_column=args.x_column,
            y_column=y_column,
            output_column=output_column,
            regions=args.region,
            anchor_width=args.anchor_width,
            smooth_lambda=args.smooth_lambda,
            weights_column=args.weights_column,
        )
    else:
        lmfit_spline.fit_global_spline(
            df=work,
            x_column=args.x_column,
            y_column=y_column,
            output_column=output_column,
            knots_every=args.knots_every,
            n_knots=args.n_knots,
            smooth_lambda=args.smooth_lambda,
            fit_range=fit_range,
            weights_column=args.weights_column,
        )
    return pd.to_numeric(work[output_column], errors="coerce").to_numpy(dtype=float)


def run_single_fit(
    base_df: pd.DataFrame,
    sampled_tau: np.ndarray,
    args: argparse.Namespace,
    active_mode: str,
    o2_fit_mask: np.ndarray | None,
) -> np.ndarray:
    if args.fit_method == "lmfit-spline":
        work = base_df.copy()
        work[args.fit_column] = sampled_tau
        return lmfit_spline_fit(work, args, y_column=args.fit_column)

    work = with_sampled_tau(base_df, args.tau_column, sampled_tau)
    fitted_tau = continuum_step2_fit(work, args, active_mode=active_mode, o2_fit_mask=o2_fit_mask)
    if not args.post_lmfit_spline:
        return fitted_tau

    work["tau_fit_us"] = fitted_tau
    return lmfit_spline_fit(work, args, y_column="tau_fit_us")


def monte_carlo_fit(base_df: pd.DataFrame, args: argparse.Namespace) -> tuple[np.ndarray, str]:
    if args.samples < 2:
        raise SystemExit("--samples must be at least 2")
    if not 0 < args.confidence < 1:
        raise SystemExit("--confidence must be between 0 and 1")

    pressure_label = args.pressure_label or infer_pressure_label(args.csv_path)
    active_mode = "lmfit-spline"
    o2_fit_mask = None
    if args.fit_method == "continuum-step2":
        active_mode = _resolve_fit_mode(_normalize_fit_mode(args.step2_mode), pressure_label)
        if active_mode == "o2-hitran":
            raise SystemExit("o2-hitran does not produce a fitted tau baseline; use --step2-mode o2.")
        if active_mode == "o2":
            base_work = with_sampled_tau(
                base_df,
                args.tau_column,
                pd.to_numeric(base_df[args.tau_column], errors="coerce").to_numpy(dtype=float),
            )
            o2_fit_mask = o2_fit_mask_from_table(base_work, pressure_label=pressure_label)

    rng = np.random.default_rng(args.seed)
    if args.fit_method == "lmfit-spline":
        y0 = pd.to_numeric(base_df[args.fit_column], errors="coerce").to_numpy(dtype=float)
    else:
        y0 = pd.to_numeric(base_df[args.tau_column], errors="coerce").to_numpy(dtype=float)
    sigma = pd.to_numeric(base_df["tau_mc_input_uncertainty_us"], errors="coerce").to_numpy(dtype=float)
    if not np.all(np.isfinite(y0) & (y0 > 0)):
        raise SystemExit("Input tau/fit column contains non-positive or non-finite values.")

    results = np.empty((args.samples, len(base_df)), dtype=float)
    report_every = max(1, args.samples // 10)
    for idx in range(args.samples):
        sampled = y0 + rng.normal(loc=0.0, scale=sigma, size=len(y0))
        sampled = np.maximum(sampled, args.min_tau_us)
        results[idx] = run_single_fit(
            base_df=base_df,
            sampled_tau=sampled,
            args=args,
            active_mode=active_mode,
            o2_fit_mask=o2_fit_mask,
        )
        if (idx + 1) % report_every == 0 or idx + 1 == args.samples:
            print(f"  MC sample {idx + 1}/{args.samples}")
    return results, active_mode


def add_mc_columns(base_df: pd.DataFrame, samples: np.ndarray, args: argparse.Namespace) -> pd.DataFrame:
    out = base_df.copy()
    prefix = args.output_prefix
    alpha = (1.0 - args.confidence) / 2.0
    low_q = 100.0 * alpha
    high_q = 100.0 * (1.0 - alpha)

    mean = np.nanmean(samples, axis=0)
    std = np.nanstd(samples, axis=0, ddof=1)
    out[f"{prefix}_mean_us"] = mean
    out[f"{prefix}_uncertainty_us"] = std
    out[f"{prefix}_rel_uncertainty"] = std / np.abs(mean)
    out[f"{prefix}_ci_low_us"] = np.nanpercentile(samples, low_q, axis=0)
    out[f"{prefix}_ci_high_us"] = np.nanpercentile(samples, high_q, axis=0)
    out[f"{prefix}_samples"] = int(args.samples)
    out[f"{prefix}_seed"] = int(args.seed)
    return out


def save_plot(out: pd.DataFrame, args: argparse.Namespace) -> None:
    if not args.plot:
        return
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    prefix = args.output_prefix
    x = pd.to_numeric(out[args.x_column], errors="coerce").to_numpy(dtype=float)
    mean = pd.to_numeric(out[f"{prefix}_mean_us"], errors="coerce").to_numpy(dtype=float)
    unc = pd.to_numeric(out[f"{prefix}_uncertainty_us"], errors="coerce").to_numpy(dtype=float)
    mask = np.isfinite(x) & np.isfinite(mean) & np.isfinite(unc)

    fig, ax = plt.subplots(figsize=(11, 5), dpi=200)
    ax.plot(x[mask], mean[mask], lw=1.3, color="tab:red", label=f"{prefix}_mean_us")
    ax.fill_between(
        x[mask],
        mean[mask] - unc[mask],
        mean[mask] + unc[mask],
        color="tab:red",
        alpha=0.22,
        linewidth=0,
        label="1 sigma",
    )
    ax.set_xlabel("Wavenumber (cm-1)")
    ax.set_ylabel("tau_fit_us")
    ax.grid(alpha=0.25)
    ax.legend()
    fig.tight_layout()
    plot_path = args.plot.expanduser().resolve()
    plot_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(plot_path)
    plt.close(fig)
    print(f"Plot: {plot_path}")


def main() -> None:
    args = parse_args()
    args.csv_path = args.csv_path.expanduser().resolve()
    output_path = (
        args.output.expanduser().resolve()
        if args.output
        else default_output_path(args.csv_path).resolve()
    )

    base_df = read_base_table(args)
    uncertainty_df = read_uncertainty_table(args)
    base_df = attach_tau_uncertainty(base_df, uncertainty_df, args)

    print(f"Input CSV: {args.csv_path}")
    print(f"Output CSV: {output_path}")
    print(f"Fit method: {args.fit_method}")
    print(f"Samples: {args.samples}")

    samples, active_mode = monte_carlo_fit(base_df, args)
    out = add_mc_columns(base_df, samples, args)
    out[f"{args.output_prefix}_fit_method"] = args.fit_method
    out[f"{args.output_prefix}_active_mode"] = active_mode

    output_path.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(output_path, index=False)
    save_plot(out, args)

    uncertainty_col = f"{args.output_prefix}_uncertainty_us"
    uncertainty = pd.to_numeric(out[uncertainty_col], errors="coerce")
    print(f"Updated rows: {len(out)}")
    print(f"Mean fitted tau uncertainty: {float(uncertainty.mean()):.8g} us")
    print(f"Median fitted tau uncertainty: {float(uncertainty.median()):.8g} us")
    print(f"Max fitted tau uncertainty: {float(uncertainty.max()):.8g} us")
    print(f"Wrote: {output_path}")


if __name__ == "__main__":
    main()
