#!/usr/bin/env python3
"""Monte Carlo uncertainty propagation for fitted CIA ringdown time.

使用说明
--------
这个脚本用于把原始平均衰荡时间的 A 类标准不确定度传播到最终拟合后的
`tau_fit_us`。核心思想是：

    1. 读取处理后的 `continuum_step2_fit.csv`。
    2. 读取 `scripts/calculate_cia_tau_uncertainty.py` 生成的
       `tau_uncertainty.csv`，获得每个波数点的 `tau_uncertainty_us`。
    3. 每次 Monte Carlo 都生成一组扰动后的衰荡时间：

           tau_i* = tau_i + N(0, u_tau_i)

    4. 对每组扰动数据重新执行相同的拟合流程。
    5. 对每个波数点统计所有拟合结果的标准差，作为拟合后衰荡时间的
       A 类标准不确定度。

默认不覆盖输入 CSV，而是生成新文件：

    <input stem>_mc_uncertainty.csv

常用命令:
    # Ar: 用 continuum Step 2 的 loss 域拟合参数做 Monte Carlo
    python scripts/monte_carlo_tau_fit_uncertainty.py \
      'output/results/continuum/CIA/333K/Ar 500Torr/continuum_step2_fit.csv' \
      --fit-method continuum-step2 \
      --step2-mode ar \
      --cia-fit-window 40 \
      --cia-fit-step 5 \
      --cia-fit-order 2 \
      --cia-fit-sigma 4 \
      --cia-fit-smooth 20 \
      --samples 300

    # O2: 用已有 O2 吸收剔除 mask，重新拟合 CIA 基线
    python scripts/monte_carlo_tau_fit_uncertainty.py \
      'output/results/continuum/CIA/273K/O2 500Torr/continuum_step2_fit.csv' \
      --fit-method continuum-step2 \
      --step2-mode o2 \
      --cia-fit-window 8 \
      --cia-fit-step 1 \
      --cia-fit-order 2 \
      --cia-fit-sigma 2 \
      --cia-fit-smooth 2 \
      --samples 300

    # 如果最终结果还经过 lmfit B-spline 平滑，在 Step 2 后继续执行同样的平滑
    python scripts/monte_carlo_tau_fit_uncertainty.py \
      'output/results/continuum/CIA/273K/Ar 500Torr/continuum_step2_fit.csv' \
      --fit-method continuum-step2 \
      --step2-mode ar \
      --cia-fit-window 40 \
      --cia-fit-step 5 \
      --cia-fit-order 2 \
      --cia-fit-sigma 4 \
      --cia-fit-smooth 20 \
      --post-lmfit-spline \
      --knots-every 15 \
      --smooth-lambda 0.1 \
      --samples 300

    # 只对某一列直接做 lmfit B-spline Monte Carlo
    python scripts/monte_carlo_tau_fit_uncertainty.py \
      'output/results/continuum/CIA/273K/Ar 500Torr/continuum_step2_fit.csv' \
      --fit-method lmfit-spline \
      --fit-column tau_us \
      --knots-every 15 \
      --smooth-lambda 0.1 \
      --samples 300

输出新增列:
    tau_mc_input_uncertainty_us
        输入平均衰荡时间的 A 类标准不确定度。
    tau_fit_us_mc_mean
        Monte Carlo 拟合结果的平均值。
    tau_fit_us_mc_uncertainty_us
        Monte Carlo 拟合结果的标准差，即拟合后衰荡时间的 A 类标准不确定度。
    tau_fit_us_mc_ci_low_us / tau_fit_us_mc_ci_high_us
        默认 95% Monte Carlo 分位区间。
"""

